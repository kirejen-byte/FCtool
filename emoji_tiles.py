"""Tile images for the bundled emoji sprite sheet (``assets/emoji/twemoji_22.png``).

The ping editor draws Discord's standard emoji as small inline images.  Every
tile lives in ONE sprite sheet generated by ``tools/build_emoji_pack.py``; this
module reads that sheet lazily, cuts a tile on demand into its own
``tk.PhotoImage``, caches it and keeps it alive.  ``emoji_data`` says which
tile a sequence owns and how the sheet is laid out -- this module knows only
the grid arithmetic::

    tile t occupies the ``tile_px`` square whose top-left is
    (1 + (t % cols) * cell_px, 1 + (t // cols) * cell_px)

An image is found through :attr:`emoji_data.Emoji.tile`, NEVER through an
entry's position in the table: a pack built without skin-tone tiles gives a
toned entry its base emoji's tile, so two entries may share one tile (and then
share one image).

**Tk never sees the sheet.**  Tk 8.6.15 needs over a MINUTE to decode it as
one ``PhotoImage`` (measured 2026-10-09: Tk rebuilds an image's "valid region"
line by line, which is superlinear in the number of transparent runs -- the
same pixels made opaque decode in under 100 ms).  So the sheet is read with
the standard library instead:

* the sheet is ALWAYS an 8-bit palette PNG (colour type 3) with a ``PLTE`` and
  a ``tRNS`` chunk, non-interlaced, and every scanline has filter type 0 -- the
  pack tool writes it that way and a test pins it.  Anything else is refused;
* its pixel rows are inflated ONCE with ``zlib`` and kept as bytes (one palette
  index per pixel -- about 2.2 MB for the real sheet).  Filter type 0 is what
  makes a tile a plain slice of those rows;
* a tile is its ``tile_px`` rows x ``tile_px`` bytes wrapped as a tiny PNG of
  its own (the sheet's ``PLTE`` and ``tRNS`` copied) and handed to
  ``tk.PhotoImage(data=...)``.  No ``PhotoImage`` larger than one tile is ever
  created, and there is no Pillow here.

**Nothing is read at import or at construction** -- no file, no table, no
logger.  The first :meth:`EmojiTiles.image` for a KNOWN sequence reads the
sheet; tiles are built one at a time (pre-building all 3,807 would cost about
12 MB, and a ping shows a handful).

Tk drops an image that no Python object references (the classic empty-label
trap), so the object holds every image it has handed out until
:meth:`EmojiTiles.release`.

A missing, corrupt or wrongly encoded sheet is never an exception and never a
dialog: ``image()`` answers None and ONE warning is logged per ``EmojiTiles``
object.  A sheet that is WRONG (damaged, wrongly encoded, too small, a layout
this module will not cut) is not tried again until ``release()``.  A sheet
that could not be READ (an ``OSError`` on the open or the read -- this box has
a history of transient opens) is tried again by the next calls, three attempts
in all, exactly as ``emoji_data`` treats its table.

Tk-thread only, like every image: a ``PhotoImage`` belongs to the interpreter
that made it, and its ``__del__`` calls back into Tcl -- create, use and
``release()`` an ``EmojiTiles`` on the thread that runs the interpreter.
"""

import os
import struct
import tkinter as tk
import zlib
from dataclasses import dataclass

import emoji_data
from app_path import resolve_data_file

#: The sprite sheet, relative to the bundle directory (forward slashes: the
#: same spelling the PyInstaller ``datas`` entry uses).
SHEET_FILE = "assets/emoji/twemoji_22.png"

_PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
_IHDR = struct.Struct(">IIBBBBB")   # width, height, depth, colour type,
#                                     compression, filter method, interlace
#: Sanity bound on either side of a sheet: the inflated rows are
#: ``(1 + width) * height`` bytes, and nothing is inflated past that.
_MAX_SIDE = 8192
#: The largest tile this module will cut.  "Tk never sees the sheet" holds only
#: while a tile is small: a table declaring one huge tile would otherwise hand
#: Tk most of the sheet in a single image (the real tiles are 22 px).
_MAX_TILE_PX = 64
#: How many times a sheet that could not be READ is tried (one try per
#: ``image()`` call) before the failure sticks -- ``emoji_data``'s number.
_MAX_READ_ATTEMPTS = 3


def _sheet_path():
    """The bundled sheet's path, or None when it is not present.

    ``prefer="bundle"``: a PRISTINE generated asset that must always read the
    packaged copy (``sys._MEIPASS`` when frozen, the source tree otherwise)."""
    path = resolve_data_file(SHEET_FILE, prefer="bundle")
    return os.path.normpath(path) if path else None


def _chunk(kind: bytes, body: bytes) -> bytes:
    """One PNG chunk: length, type, body, CRC over type + body."""
    return (struct.pack(">I", len(body)) + kind + body
            + struct.pack(">I", zlib.crc32(body, zlib.crc32(kind))))


class _Sheet:
    """A sheet as this module keeps it: the inflated scanlines (each one
    filter byte, always 0, then ``width`` palette indices) and the two chunks
    every tile PNG copies."""
    __slots__ = ("width", "height", "stride", "rows", "plte", "trns")


def _parse_sheet(data: bytes) -> _Sheet:
    """Check ``data`` is a sheet in the one encoding this module reads and
    inflate its rows. Raises ``ValueError`` naming the first thing that is
    wrong (and ``zlib.error`` on a damaged pixel stream)."""
    if data[:8] != _PNG_SIGNATURE:
        raise ValueError("not a PNG file")
    header = plte = trns = None
    idat = []
    ended = False
    size = len(data)
    pos = 8
    while pos < size:
        if pos + 12 > size:
            raise ValueError("truncated: a chunk header is cut short")
        length, kind = struct.unpack_from(">I4s", data, pos)
        end = pos + 12 + length
        if end > size:
            raise ValueError("truncated: chunk %r is cut short" % (kind,))
        body = data[pos + 8:end - 4]
        if zlib.crc32(body, zlib.crc32(kind)) != struct.unpack_from(
                ">I", data, end - 4)[0]:
            raise ValueError("chunk %r fails its CRC" % (kind,))
        if header is None:
            if kind != b"IHDR" or length != _IHDR.size:
                raise ValueError("the first chunk is not an IHDR")
            header = _IHDR.unpack(body)
        elif kind == b"PLTE":
            plte = body
        elif kind == b"tRNS":
            trns = body
        elif kind == b"IDAT":
            idat.append(body)
        elif kind == b"IEND":
            ended = True
            break
        pos = end
    if header is None or not ended:
        raise ValueError("truncated: no IEND chunk")

    width, height, depth, colour, compression, filtering, interlace = header
    if depth != 8 or colour != 3:
        raise ValueError("is %d-bit colour type %d; the sheet must be an "
                         "8-bit palette PNG (colour type 3)" % (depth, colour))
    if compression or filtering:
        raise ValueError("unknown compression or filter method")
    if interlace:
        raise ValueError("is interlaced; the sheet must not be")
    if not (0 < width <= _MAX_SIDE and 0 < height <= _MAX_SIDE):
        raise ValueError("is %dx%d; a side must be 1..%d"
                         % (width, height, _MAX_SIDE))
    if not plte or len(plte) % 3 or len(plte) > 768:
        raise ValueError("has no usable PLTE chunk")
    if trns is None:
        raise ValueError("has no tRNS chunk")
    if len(trns) > len(plte) // 3:
        raise ValueError("tRNS is longer than the palette")
    if not idat:
        raise ValueError("has no IDAT chunk")

    stride = 1 + width
    expected = stride * height
    inflater = zlib.decompressobj()
    rows = inflater.decompress(b"".join(idat), expected + 1)
    if len(rows) != expected or not inflater.eof:
        raise ValueError("pixel data does not inflate to exactly %d bytes"
                         % expected)
    if any(rows[::stride]):
        raise ValueError("a scanline uses a PNG filter; every scanline must "
                         "have filter type 0")

    sheet = _Sheet()
    sheet.width, sheet.height, sheet.stride = width, height, stride
    sheet.rows, sheet.plte, sheet.trns = rows, plte, trns
    return sheet


def _read_bytes(path) -> bytes:
    """The file's raw bytes. The ONLY disk access of a load, kept apart from
    :func:`_parse_sheet` so that an ``OSError`` here means "could not read"
    (worth another try) and never "bad content".  Also the seam the read-once
    and retry contracts are spied on through."""
    with open(path, "rb") as fh:
        return fh.read()


def _check_layout(layout) -> None:
    """Raise unless ``layout`` is a grid this module will cut tiles from:
    whole numbers, a tile of 1..``_MAX_TILE_PX`` px that fits its cell, at
    least one column and one tile.  (No layout at all raises too.)"""
    values = (layout.tile_px, layout.cell_px, layout.cols, layout.tiles)
    if not all(isinstance(value, int) and not isinstance(value, bool)
               for value in values):
        raise ValueError("tile_px, cell_px, cols, tiles must be whole "
                         "numbers, got %r" % (values,))
    tile_px, cell_px, cols, tiles = values
    if not 1 <= tile_px <= _MAX_TILE_PX:
        raise ValueError("tile_px is %d; a tile must be 1..%d px"
                         % (tile_px, _MAX_TILE_PX))
    if tile_px > cell_px:
        raise ValueError("tile_px %d exceeds cell_px %d" % (tile_px, cell_px))
    if cols < 1 or tiles < 1:
        raise ValueError("cols is %d and tiles is %d; both must be at least 1"
                         % (cols, tiles))


def _ascii(value) -> str:
    """``value`` as pure-ASCII text for a log line: this box's console is
    cp1252, and a path or a message carrying anything else makes the stream
    handler print a "Logging error" traceback."""
    return str(value).encode("ascii", "backslashreplace").decode("ascii")


def _log(level: str, message, *args) -> None:
    """One line through the house logger -- fetched HERE, never at import,
    because its first call opens the log file.  Never raises."""
    try:
        from app_log import get_logger
        getattr(get_logger(__name__), level)(message, *args)
    except Exception:
        pass


def _needed_size(layout) -> tuple:
    """The smallest (width, height) a sheet must have to hold every tile of
    ``layout`` -- the bottom-right corner of the last column / last row."""
    last = layout.tiles - 1
    columns = min(layout.cols, layout.tiles)
    width = 1 + (columns - 1) * layout.cell_px + layout.tile_px
    height = 1 + (last // layout.cols) * layout.cell_px + layout.tile_px
    return width, height


class EmojiTiles:
    """The tile images of one sprite sheet, for one Tk interpreter.

    ``master`` is any widget of the interpreter the images are for.
    ``sheet_path`` / ``layout`` override the bundled sheet and the table's
    :class:`emoji_data.SheetLayout`; both default to "ask when first needed",
    so constructing one reads nothing."""

    def __init__(self, master, *, sheet_path=None, layout=None):
        self._master = master
        self._sheet_arg = None if sheet_path is None else os.fspath(sheet_path)
        self._layout_arg = layout
        self._sheet = None          # the inflated sheet (_Sheet), or None
        self._layout = None         # the layout the sheet was checked against
        self._head = b""            # a tile PNG up to its IDAT chunk
        self._cache = {}            # tile number -> PhotoImage (the keep-alive)
        self._failed = False        # the sheet is unusable; do not try again
        self._attempts = 0          # reads tried since the last release()
        self._warned = False        # the one WARNING has been logged

    def image(self, seq: str) -> "tk.PhotoImage | None":
        """The tile for an emoji sequence (fully-qualified or an ``alt`` form),
        or None for an unknown sequence or an unusable sheet.

        The same object for the same sequence until :meth:`release`; entries
        that share a tile share the object.  Never raises -- not even when
        ``emoji_data`` or Tk does (a destroyed interpreter): that is None for
        this call."""
        try:
            entry = emoji_data.lookup(seq)
            if entry is None:
                return None
            tile = entry.tile
            cached = self._cache.get(tile)
            if cached is not None:
                return cached
            if self._sheet is None and not self._load():
                return None
            image = self._make_tile(tile)
        except Exception:
            return None
        if image is not None:
            self._cache[tile] = image
        return image

    def loaded(self) -> bool:
        """Whether the sheet's rows are read and held right now."""
        return self._sheet is not None

    def release(self) -> None:
        """Drop the sheet's rows and every cached tile; a later :meth:`image`
        reloads (and tries a sheet that failed before afresh -- the WARNING
        stays one per object).

        Images already on screen go blank -- Tk deletes an image when its last
        Python reference goes -- so call this when the window that shows them
        closes, on the Tk thread."""
        self._cache = {}
        self._sheet = None
        self._layout = None
        self._head = b""
        self._failed = False
        self._attempts = 0

    # -- internals ---------------------------------------------------------

    def _load(self) -> bool:
        """Make the sheet ready, or answer False after ONE warning. Never
        raises.

        A layout this module will not cut, a damaged or wrongly encoded sheet
        and a sheet too small for the layout are WRONG: the failure sticks
        until :meth:`release`, so a redraw does not re-read a bad file per
        emoji.  An ``OSError`` on the open or the read may be transient: the
        next call tries again, ``_MAX_READ_ATTEMPTS`` tries in all."""
        if self._failed:
            return False
        try:
            layout = self._layout_arg
            if layout is None:
                layout = emoji_data.sheet_layout()
            _check_layout(layout)
        except Exception as exc:
            return self._fail(True, "[Emoji] the emoji tile layout is "
                              "unusable (%s: %s); emoji are shown as plain "
                              "characters", type(exc).__name__, _ascii(exc))

        self._attempts += 1
        path = self._sheet_arg
        try:
            if path is None:
                path = _sheet_path()
            if not path:
                raise FileNotFoundError("not found beside the app")
            data = _read_bytes(path)
        except OSError as exc:
            # ``strerror`` alone: the full text would repeat the path.
            return self._fail(
                self._attempts >= _MAX_READ_ATTEMPTS,
                "[Emoji] %s could not be read (%s: %s); emoji are shown as "
                "plain characters", _ascii(path or SHEET_FILE),
                type(exc).__name__, _ascii(exc.strerror or exc))
        except Exception as exc:                # a path that is no path at all
            return self._fail(True, "[Emoji] %s could not be located (%s: "
                              "%s); emoji are shown as plain characters",
                              SHEET_FILE, type(exc).__name__, _ascii(exc))

        try:
            sheet = _parse_sheet(data)
            need_w, need_h = _needed_size(layout)
            if sheet.width < need_w or sheet.height < need_h:
                raise ValueError("is %dx%d but the emoji table needs at least "
                                 "%dx%d" % (sheet.width, sheet.height,
                                            need_w, need_h))
            size = layout.tile_px
            head = (_PNG_SIGNATURE
                    + _chunk(b"IHDR", _IHDR.pack(size, size, 8, 3, 0, 0, 0))
                    + _chunk(b"PLTE", sheet.plte)
                    + _chunk(b"tRNS", sheet.trns))
        except Exception as exc:
            return self._fail(True, "[Emoji] %s is unusable (%s: %s); emoji "
                              "are shown as plain characters", _ascii(path),
                              type(exc).__name__, _ascii(exc))
        if self._attempts > 1:
            _log("info", "[Emoji] %s read on attempt %d", _ascii(path),
                 self._attempts)
        self._sheet = sheet
        self._layout = layout
        self._head = head
        return True

    def _fail(self, settled: bool, message, *args) -> bool:
        """Log the one WARNING and answer False; ``settled`` makes the
        failure stick until :meth:`release`."""
        if settled:
            self._failed = True
        if not self._warned:
            self._warned = True
            _log("warning", message, *args)
        return False

    def _make_tile(self, tile):
        """A new ``PhotoImage`` of ``tile``, or None when the tile lies outside
        the layout: the tile's rows sliced out of the sheet's, wrapped as a
        PNG of their own. The only place an image is created."""
        layout = self._layout
        if not 0 <= tile < layout.tiles:
            return None
        sheet = self._sheet
        size = layout.tile_px
        stride = sheet.stride
        rows = sheet.rows
        # +1: each scanline starts with its filter byte.
        first = ((1 + (tile // layout.cols) * layout.cell_px) * stride
                 + 1 + 1 + (tile % layout.cols) * layout.cell_px)
        body = b"".join(b"\x00" + rows[start:start + size]
                        for start in range(first, first + size * stride,
                                           stride))
        png = (self._head + _chunk(b"IDAT", zlib.compress(body, 1))
               + _chunk(b"IEND", b""))
        image = tk.PhotoImage(master=self._master, data=png)
        # Tk keeps the ``-data`` value for the image's whole life; clearing
        # the option keeps the decoded pixels and frees it -- measured
        # 2026-10-09 on the real pack: 8.8 KB -> 3.0 KB per tile.
        try:
            image.configure(data="")
        except tk.TclError:
            pass
        return image


@dataclass(frozen=True)
class EmojiHooks:
    """The three callables the ping editor's canvas needs to draw emoji --
    handed over as one object so the canvas imports no emoji module."""
    split: object            # emoji_data.split
    image: object            # EmojiTiles.image
    from_shortcode: object   # emoji_data.from_shortcode


def _probe_seq() -> "str | None":
    """The table's first entry - the sequence :func:`make_hooks` cuts to find
    out whether the sheet is usable. None for a table that names no emoji."""
    for _name, members in emoji_data.groups(include_tones=True):
        for entry in members:
            return entry.seq
    return None


def make_hooks(master) -> "tuple[EmojiHooks, EmojiTiles] | None":
    """Hooks drawing from the bundled pack, plus the :class:`EmojiTiles` behind
    them (the caller ``release()``s it when its window closes).

    None when the pack cannot DRAW: ``emoji_data.available()`` is False, or
    the sprite sheet is missing, damaged or unreadable. A table without its
    sheet must not hand out hooks - its owner would recognise every emoji and
    then draw each one as text, which Tk does slowly (a picker page of 54
    took 0.5-2 s); with no hooks the owner shows plain characters instead.

    So this is where the pack is read, once, when a window that shows emoji
    opens (nothing happens at import): the table, then the sheet, by cutting
    ONE known tile - the table's first entry. A sheet that merely could not
    be READ is tried again, ``_MAX_READ_ATTEMPTS`` tries in all, as
    :meth:`EmojiTiles.image` would on later calls. The probed tile stays
    cached. Never raises."""
    try:
        if not emoji_data.available():
            return None
        seq = _probe_seq()
        if seq is None:
            return None
        tiles = EmojiTiles(master)
        for _attempt in range(_MAX_READ_ATTEMPTS):
            if tiles.image(seq) is not None:
                return (EmojiHooks(split=emoji_data.split, image=tiles.image,
                                   from_shortcode=emoji_data.from_shortcode),
                        tiles)
            if tiles._failed:           # the sheet is WRONG: no second try
                break
        tiles.release()
    except Exception:
        pass
    return None
