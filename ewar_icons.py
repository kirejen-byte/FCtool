"""The bundled EWAR module icons (``assets/ewar/ewar_icons.png``).

The preview's EWAR popup paints a row of small EVE module icons over a tile.
Every icon lives in ONE sprite sheet generated by ``tools/build_ewar_icons.py``
from CCP's official image server; this module decodes that sheet with the
standard library and hands out one cell at a time as raw bytes.

    icon_rgba(effect, px) -> exactly ``px * px * 4`` bytes of STRAIGHT RGBA,
                             or None

**Straight, not premultiplied.**  The consumer is a Win32 layered window, which
needs premultiplied BGRA -- but the premultiply (and the dark chip, and the red
hairline border) belong to the popup, which composes them while it builds its
DIB.  This module only ever reports what the artwork says.

THE LAYOUT IS THE CONTRACT.  Nothing is read out of the file but its IHDR: the
rows are the effects in :data:`ewar_parse.ICON_ORDER`, the columns are the sizes
in :data:`ICON_SIZES`, and cell ``(i, j)`` is the ``ICON_SIZES[j]`` square whose
top-left pixel is ``(sum(ICON_SIZES[:j]), i * max(ICON_SIZES))``.  A sheet of
any other size is refused whole.  That is what makes the art replaceable as an
asset edit rather than a code change -- CCP's licence lets it withdraw material
on seven days' notice, and ``assets/ewar/NOTICE.txt`` carries the type IDs and
the layout so the set can be regenerated or swapped without reading any code.

**The sheet is truecolour RGBA (colour type 6, bit depth 8) and nothing else.**
``emoji_tiles.py`` is NOT reusable here and was not reused: it accepts 8-bit
palette PNGs only and exists to hand ``PhotoImage`` objects to Tk widgets,
whereas this art is truecolour-with-alpha and its consumer paints raw bytes.
Only the stdlib-PNG technique is shared.

**Nothing here raises, ever.**  This sits on the preview tick path, where an
exception retires the tile and five failed ticks disable every preview.  A
missing, corrupt or wrongly encoded sheet makes every call answer None, and the
popup then draws nothing -- absent icons are a cosmetic loss, a dead tile is
not.

The whole sheet is about 21 KB, so it is decoded ONCE at import and every cell
is kept (about 34 KB in all).  No call touches the filesystem, and there is no
lazy path to get wrong.  The cells are immutable ``bytes``, so handing the same
object to several callers on several threads is safe.
"""

import os
import struct
import zlib

from app_path import bundle_dir
from ewar_parse import ICON_ORDER

#: The icon sizes the sheet carries, ascending.  14 and 18 px are the design's
#: sizes at 100% Tk scaling (18 on tiles >= 200 px wide, 14 below that); 21 and
#: 27 are the same two at 150%.  The tile picks one and snaps to this tuple --
#: the art is pre-rendered offline at exactly these sizes rather than scaled at
#: paint time, because a resample per tick is work the tick cannot afford.
ICON_SIZES = (14, 18, 21, 27)

#: The sheet, relative to the bundle directory.  Forward slashes: the same
#: spelling the PyInstaller ``datas`` entry uses.
SHEET_FILE = "assets/ewar/ewar_icons.png"

_PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
#: width, height, bit depth, colour type, compression, filter method, interlace
_IHDR = struct.Struct(">IIBBBBB")
#: The only encoding accepted: 8-bit truecolour RGBA, deflate, adaptive
#: filtering, non-interlaced.
_ACCEPTED_IHDR_TAIL = (8, 6, 0, 0, 0)
#: Sanity bound on either side of a sheet -- the real one is 80 x 135.  Keeps a
#: malformed IHDR from asking for a gigabyte of scanlines.
_MAX_SIDE = 1024
#: Bytes per pixel in 8-bit RGBA; the filter reach.
_BPP = 4


def _decode_rgba_png(data):
    """``(width, height, rgba)`` for an 8-bit truecolour-RGBA PNG, else None.

    ``rgba`` is ``width * height * 4`` bytes, top-down, straight alpha.  Parses
    IHDR, concatenates every IDAT, inflates once and undoes the five per-
    scanline filters.  Anything else -- another colour type, another bit depth,
    interlacing, a file truncated mid-chunk, a deflate stream that never
    properly ended or whose checksum failed, an unknown filter byte, rows that
    do not add up -- is None, never an exception."""
    try:
        if not isinstance(data, (bytes, bytearray, memoryview)):
            return None
        data = bytes(data)
        if not data.startswith(_PNG_SIGNATURE):
            return None
        pos = len(_PNG_SIGNATURE)
        width = height = 0
        seen_ihdr = False
        idat = []
        while pos + 8 <= len(data):
            (length,) = struct.unpack_from(">I", data, pos)
            tag = data[pos + 4:pos + 8]
            start = pos + 8
            end = start + length
            if end + 4 > len(data):
                return None                     # truncated mid-chunk
            chunk = data[start:end]
            pos = end + 4                       # skip the CRC
            if tag == b"IHDR":
                if seen_ihdr or length != _IHDR.size:
                    return None
                width, height = _IHDR.unpack(chunk)[:2]
                if _IHDR.unpack(chunk)[2:] != _ACCEPTED_IHDR_TAIL:
                    return None
                if not (0 < width <= _MAX_SIDE and 0 < height <= _MAX_SIDE):
                    return None
                seen_ihdr = True
            elif tag == b"IDAT":
                if not seen_ihdr:
                    return None
                idat.append(chunk)
            elif tag == b"IEND":
                break
        if not seen_ihdr or not idat:
            return None
        stride = width * _BPP
        wanted = (stride + 1) * height
        # BOUNDED inflate.  NOTICE.txt invites a third party to drop a
        # replacement sheet in, so a hostile or merely broken IDAT is a
        # reachable input, not a theoretical one -- and a 122 KB file whose
        # IDAT expands 1000:1 peaks at hundreds of MB if the size is only
        # checked afterwards.  ``decompressobj`` stops at the byte after the
        # one valid sheet's worth, and anything that long is refused below.
        #
        # ``eof`` IS LOAD-BEARING, not belt and braces.  Unlike one-shot
        # ``zlib.decompress``, a decompressobj does not complain about a
        # truncated stream: it just returns what it got.  Cut the last bytes
        # off a real IDAT and the output is still exactly ``wanted`` long, so
        # the length check passes -- and because the stream never reached its
        # end, the adler32 trailer is never verified, which is what would
        # otherwise have caught the corruption.  ``eof`` is True only when the
        # deflate stream ended properly and that checksum matched.
        decomp = zlib.decompressobj()
        raw = decomp.decompress(b"".join(idat), wanted + 1)
        if not decomp.eof or len(raw) != wanted:
            return None
        out = bytearray(stride * height)
        prev = bytearray(stride)
        src = 0
        for y in range(height):
            kind = raw[src]
            src += 1
            line = bytearray(raw[src:src + stride])
            src += stride
            if kind == 0:                       # None
                pass
            elif kind == 1:                     # Sub
                for i in range(_BPP, stride):
                    line[i] = (line[i] + line[i - _BPP]) & 0xFF
            elif kind == 2:                     # Up
                for i in range(stride):
                    line[i] = (line[i] + prev[i]) & 0xFF
            elif kind == 3:                     # Average
                for i in range(stride):
                    left = line[i - _BPP] if i >= _BPP else 0
                    line[i] = (line[i] + ((left + prev[i]) >> 1)) & 0xFF
            elif kind == 4:                     # Paeth
                for i in range(stride):
                    a = line[i - _BPP] if i >= _BPP else 0
                    b = prev[i]
                    c = prev[i - _BPP] if i >= _BPP else 0
                    p = a + b - c
                    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                    if pa <= pb and pa <= pc:
                        pred = a
                    elif pb <= pc:
                        pred = b
                    else:
                        pred = c
                    line[i] = (line[i] + pred) & 0xFF
            else:
                return None                     # not a PNG filter type
            out[y * stride:(y + 1) * stride] = line
            prev = line
        return width, height, bytes(out)
    except Exception:
        return None


def _expected_size():
    """The only dimensions a sheet may have, from the two canonical tuples."""
    return sum(ICON_SIZES), len(ICON_ORDER) * max(ICON_SIZES)


def _slice_cells(width, height, rgba):
    """``{(effect, px): bytes}`` cut from a decoded sheet, or ``{}`` when the
    sheet is not this layout."""
    if (width, height) != _expected_size():
        return {}
    stride = width * _BPP
    cell_h = max(ICON_SIZES)
    cells = {}
    for row, effect in enumerate(ICON_ORDER):
        top = row * cell_h
        left = 0
        for px in ICON_SIZES:
            span = px * _BPP
            buf = bytearray(px * span)
            for y in range(px):
                src = (top + y) * stride + left * _BPP
                buf[y * span:(y + 1) * span] = rgba[src:src + span]
            cells[(effect, px)] = bytes(buf)
            left += px
    return cells


def _load_cells():
    """Every cell of the bundled sheet, or ``{}`` -- never an exception."""
    try:
        path = os.path.join(bundle_dir(), *SHEET_FILE.split("/"))
        with open(path, "rb") as fh:
            data = fh.read()
    except Exception:
        return {}
    decoded = _decode_rgba_png(data)
    if decoded is None:
        return {}
    try:
        return _slice_cells(*decoded)
    except Exception:
        return {}


#: Decoded once, at import.  Empty when the sheet is absent or unusable, which
#: is the whole of this module's failure handling.
_CELLS = _load_cells()


def icon_rgba(effect, px):
    """``px * px * 4`` bytes of straight RGBA for one effect, or None.

    None for an effect the sheet does not carry, a size that was not
    pre-rendered, a value of the wrong type, or a sheet that could not be read.
    Never raises; the same call always returns the same object."""
    try:
        return _CELLS.get((effect, px))
    except Exception:
        # Not just TypeError: hashing the key runs the ARGUMENT's ``__hash__``,
        # and an object whose ``__hash__`` raises ValueError (or anything else)
        # would otherwise escape into the preview tick and retire the tile.
        return None
