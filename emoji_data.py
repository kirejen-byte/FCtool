"""Lazy, thread-safe reader for the bundled emoji table (``emoji_table.json.gz``).

The table is Discord's standard emoji set -- Emoji 16.0's fully-qualified
sequences plus the 26 regional-indicator letters -- with each emoji's CLDR
name, Discord shortcodes, group and sprite-sheet tile.  It is generated by
``tools/build_emoji_pack.py``; this module is the ONLY thing that knows the
wire encoding.  Consumers (the ping editor's canvas, the tile cache, the
picker) go through the functions below.

Pure: the standard library and ``app_path`` only -- no Tk, no network, no
``fc_gui``.  (``app_log`` is imported inside the one function that emits the
one WARNING, never at import.)

**Importing this module opens no file and fetches no logger.**  The table is
decoded on the first call that needs it, once, under a lock; concurrent first
callers decode exactly once.  A missing, corrupt or misshaped table is never an
exception: the module logs ONE warning and then answers "no emoji" everywhere
(``available()`` False, ``split`` returns the text as one text chunk, lookups
return None) until :func:`set_data_file` points it somewhere else.

Wire encoding (gzip, UTF-8 JSON)::

    {"version": 1, "emoji_version": "16.0",
     "tile_px": 22, "cell_px": 24, "cols": 62,
     "count": <entries>, "tiles": <tiles in the sheet>,
     "emoji": [[seq, name, [shortcode, ...], group, tile], ...],
     "alt":   {"<not fully-qualified sequence>": position in "emoji", ...}}

``tile`` is explicit per entry and is NOT always the entry's position (a pack
built without skin-tone tiles gives a toned entry its base emoji's tile), so an
image is always found through :attr:`Emoji.tile`.

What counts as an emoji in text (:func:`split`)
-----------------------------------------------
The longest table sequence at each position, over the fully-qualified
sequences and the ``alt`` (minimally-qualified / unqualified) forms, with one
exception that keeps ordinary typing ordinary: **a single code point below
U+1F000 is an emoji only when it is ITSELF a fully-qualified entry** (the
characters with default emoji presentation -- the check mark U+2705, the star
U+2B50 and their like).  A single code point below U+1F000 that is only an
``alt`` form never matches, so a digit, ``#``, ``*``, the copyright, registered
and trade-mark signs and a bare U+2620 stay text; each becomes an emoji only as
part of a longer sequence (U+2620 U+FE0F, a keycap).
"""

import gzip
import json
import os
import re
import threading
from dataclasses import dataclass

from app_path import resolve_data_file

DATA_FILE = "emoji_table.json.gz"

#: The only wire version this reader understands.
_TABLE_VERSION = 1

#: Below this, a single code point that is only an ``alt`` form is never an
#: emoji (see the module docstring).  U+1F000 is where the pictographic planes
#: start; nothing below it that lacks default emoji presentation is something a
#: user means as a picture when it stands alone.
_TEXT_SINGLE_LIMIT = 0x1F000

_VS16 = chr(0xFE0F)
_TONE_FIRST, _TONE_LAST = 0x1F3FB, 0x1F3FF          # skin-tone modifiers 1..5
_TONE_RE = re.compile("[%s-%s]" % (chr(_TONE_FIRST), chr(_TONE_LAST)))

#: ``name::skin-tone-N`` -- Discord's long spelling of a toned emoji.
_TONE_SUFFIX_RE = re.compile(r"skin-tone-([1-5])")
#: The same suffix as it follows a ``:name:`` in running text.
_TONE_TAIL_RE = re.compile(r":skin-tone-([1-5]):", re.IGNORECASE)

#: One step of :func:`replace_shortcodes`: a ``<...>`` token (a Discord
#: timestamp, mention or custom emoji -- never touched) or a ``:name:``
#: candidate.  A token holds no whitespace, so ``1 < 2 :x: 3 > 2`` is not one.
_CODE_RE = re.compile(r"<[^<>\s]+>|:([^\s:<>]+):")


@dataclass(frozen=True)
class Emoji:
    """One table entry. ``tile`` is the entry's sheet tile (see the module
    docstring), ``shortcodes`` its Discord names without colons."""
    seq: str
    name: str
    shortcodes: tuple
    tile: int
    group: str


@dataclass(frozen=True)
class SheetLayout:
    """The sprite sheet's grid: ``tiles`` tiles of ``tile_px`` in ``cell_px``
    cells, ``cols`` to a row."""
    tile_px: int
    cell_px: int
    cols: int
    tiles: int


# --------------------------------------------------------------------------
# the decoded table
# --------------------------------------------------------------------------

class _Index:
    """Everything derived from one table, built once at load so that no call
    after it scans more than it has to.  Immutable after :func:`_build`."""
    __slots__ = ("layout", "by_seq", "alt", "by_code", "match", "lengths",
                 "find_start", "rows", "groups_all", "groups_plain")


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _start_pattern(chars):
    """A compiled character class matching exactly ``chars`` (code points
    folded into ranges), used to jump straight to the next position where an
    emoji could start."""
    points = sorted(ord(ch) for ch in chars)
    parts = []
    i = 0
    while i < len(points):
        j = i
        while j + 1 < len(points) and points[j + 1] == points[j] + 1:
            j += 1
        first, last = re.escape(chr(points[i])), re.escape(chr(points[j]))
        parts.append(first if i == j else first + "-" + last)
        i = j + 1
    return re.compile("[" + "".join(parts) + "]")


def _build(table) -> _Index:
    """Validate ``table`` and index it. Raises ``ValueError`` on any shape
    problem; :func:`_load` turns that into "unavailable"."""
    if not isinstance(table, dict):
        raise ValueError("top level is %s, expected object" % type(table).__name__)
    if table.get("version") != _TABLE_VERSION:
        raise ValueError("table version is %r, expected %d"
                         % (table.get("version"), _TABLE_VERSION))
    for key in ("tile_px", "cell_px", "cols", "tiles"):
        if not _is_int(table.get(key)) or table[key] <= 0:
            raise ValueError("%r is %r, expected a positive integer"
                             % (key, table.get(key)))
    raw = table.get("emoji")
    raw_alt = table.get("alt")
    if not isinstance(raw, list) or not raw:
        raise ValueError("'emoji' is missing or empty")
    if not isinstance(raw_alt, dict):
        raise ValueError("'alt' is missing or not an object")
    if "count" in table and table["count"] != len(raw):
        raise ValueError("'count' is %r but there are %d entries"
                         % (table["count"], len(raw)))

    entries = []
    by_seq = {}
    by_code = {}
    for position, row in enumerate(raw):
        if not isinstance(row, (list, tuple)) or len(row) < 5:
            raise ValueError("entry %d is misshaped" % position)
        seq, name, codes, group, tile = row[:5]
        if not (isinstance(seq, str) and seq
                and isinstance(name, str) and isinstance(group, str)
                and isinstance(codes, (list, tuple))
                and all(isinstance(code, str) for code in codes)
                and _is_int(tile) and 0 <= tile < table["tiles"]):
            raise ValueError("entry %d is misshaped" % position)
        entry = Emoji(seq, name, tuple(codes), tile, group)
        entries.append(entry)
        by_seq.setdefault(seq, entry)
        for code in codes:
            by_code.setdefault(code.lower(), seq)

    alt = {}
    for key, position in raw_alt.items():
        if not (isinstance(key, str) and key and _is_int(position)
                and 0 <= position < len(entries)):
            raise ValueError("alt form %r is misshaped" % (key,))
        if key not in by_seq:
            alt[key] = entries[position]

    # What split() may match: every fully-qualified sequence, and every alt
    # form EXCEPT a single code point below the pictographic planes.
    match = set(by_seq)
    for key in alt:
        if len(key) == 1 and ord(key) < _TEXT_SINGLE_LIMIT:
            continue
        match.add(key)
    by_start = {}
    for seq in match:
        by_start.setdefault(seq[0], set()).add(len(seq))

    rows = []
    groups_all = {}
    groups_plain = {}
    for entry in entries:
        toned = _TONE_RE.search(entry.seq) is not None
        rows.append((entry, tuple(code.lower() for code in entry.shortcodes),
                     entry.name.lower(), toned))
        groups_all.setdefault(entry.group, []).append(entry)
        if not toned:
            groups_plain.setdefault(entry.group, []).append(entry)

    index = _Index()
    index.layout = SheetLayout(table["tile_px"], table["cell_px"],
                               table["cols"], table["tiles"])
    index.by_seq = by_seq
    index.alt = alt
    index.by_code = by_code
    index.match = frozenset(match)
    index.lengths = {first: tuple(sorted(lengths, reverse=True))
                     for first, lengths in by_start.items()}
    index.find_start = _start_pattern(by_start).search
    index.rows = tuple(rows)
    index.groups_all = tuple((name, tuple(members))
                             for name, members in groups_all.items())
    index.groups_plain = tuple((name, tuple(members))
                               for name, members in groups_plain.items())
    return index


# --------------------------------------------------------------------------
# module state + loading
# --------------------------------------------------------------------------

_UNSET = object()

#: ``_UNSET`` until the first call that needs the table; afterwards the
#: :class:`_Index`, or None when the table could not be used.  Rebound as a
#: whole (never mutated), so a reader needs no lock.
_cache = _UNSET
#: :func:`set_data_file`'s path, or None for the bundled copy.
_override = None
_lock = threading.Lock()


def _data_path():
    """The table's path, or None when the bundled copy is not present.

    ``prefer="bundle"``: a PRISTINE generated table that must always read the
    packaged copy and never be shadowed by a stray file in the writable dir."""
    if _override is not None:
        return _override
    return resolve_data_file(DATA_FILE, prefer="bundle")


def _decode(path):
    """Read + gunzip + parse. Raises on any I/O or JSON problem; :func:`_load`
    is the layer that turns that into "unavailable". Split out so the
    load-once contract can be spied on in tests."""
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        return json.load(fh)


def _warn(message, *args) -> None:
    """The one WARNING, through the house logger -- fetched HERE, never at
    import, because its first call opens the log file.  Never raises."""
    try:
        from app_log import get_logger
        get_logger(__name__).warning(message, *args)
    except Exception:
        pass


def _load():
    """Decode and index the table, or warn once and answer None. Never raises.
    Called with ``_lock`` held."""
    try:
        path = _data_path()
        if not path:
            _warn("[Emoji] %s not found; emoji are shown as plain characters",
                  DATA_FILE)
            return None
        return _build(_decode(path))
    except Exception as exc:
        _warn("[Emoji] %s is unusable (%s: %s); emoji are shown as plain "
              "characters", DATA_FILE, type(exc).__name__, exc)
        return None


def _table():
    """The index, loading it on first use; None when there is no usable table."""
    global _cache
    cache = _cache
    if cache is not _UNSET:
        return cache
    with _lock:
        if _cache is _UNSET:
            _cache = _load()
        return _cache


def set_data_file(path) -> None:
    """Test seam: read the table from ``path`` instead of the bundled copy
    (``None`` restores the bundled copy) and forget whatever was loaded.
    Reads nothing itself -- the next call that needs the table does."""
    global _cache, _override
    with _lock:
        _override = None if path is None else os.fspath(path)
        _cache = _UNSET


def available() -> bool:
    """Whether a usable table is loaded (loading it if this is the first call).
    False when it is missing or corrupt -- one WARNING is logged, once."""
    return _table() is not None


def sheet_layout() -> "SheetLayout | None":
    """The sprite sheet's grid, or None without a table."""
    index = _table()
    return None if index is None else index.layout


# --------------------------------------------------------------------------
# sequences
# --------------------------------------------------------------------------

def split(text: str) -> list:
    """``text`` as ``[(is_emoji, chunk), ...]`` with ``"".join(chunks) == text``.

    Each emoji chunk is ONE complete sequence exactly as it appears in ``text``
    (an unqualified form is reported as typed); neighbouring text is one chunk.
    Empty text gives ``[]``.  Without a table the whole text is one text chunk.
    See the module docstring for what counts as an emoji."""
    if not text:
        return []
    index = _table()
    if index is None:
        return [(False, text)]
    find_start = index.find_start
    lengths = index.lengths
    match = index.match
    out = []
    pos = 0             # where the search for the next emoji resumes
    pending = 0         # start of the text not yet emitted
    while True:
        hit = find_start(text, pos)
        if hit is None:
            break
        at = hit.start()
        for length in lengths[text[at]]:
            chunk = text[at:at + length]
            if chunk in match:
                if pending < at:
                    out.append((False, text[pending:at]))
                out.append((True, chunk))
                pos = pending = at + len(chunk)
                break
        else:
            pos = at + 1
    if pending < len(text):
        out.append((False, text[pending:]))
    return out


def lookup(seq: str) -> "Emoji | None":
    """The entry for a sequence, fully-qualified or ``alt`` form; else None.

    A plain table lookup: the single-code-point rule of :func:`split` does not
    apply, so a bare U+2620 finds the skull-and-crossbones entry."""
    index = _table()
    if index is None or not isinstance(seq, str):
        return None
    entry = index.by_seq.get(seq)
    return entry if entry is not None else index.alt.get(seq)


# --------------------------------------------------------------------------
# shortcodes
# --------------------------------------------------------------------------

def _toned(index, base: str, tone: int) -> "str | None":
    """The sequence for shortcode ``base`` (lower-case) in skin tone 1..5, or
    None when the table has no such emoji.

    Discord's own ``<base>_tone<N>`` name first; failing that the sequence is
    built -- modifier after the first code point, a VS16 there dropped -- and
    accepted only if it is a table entry."""
    seq = index.by_code.get("%s_tone%d" % (base, tone))
    if seq is not None:
        return seq
    plain = index.by_code.get(base)
    if plain is None:
        return None
    rest = plain[1:]
    if rest.startswith(_VS16):
        rest = rest[1:]
    built = plain[0] + chr(_TONE_FIRST + tone - 1) + rest
    return built if built in index.by_seq else None


def from_shortcode(name: str) -> "str | None":
    """The sequence for a Discord shortcode given WITHOUT colons, or None.

    Case-insensitive. ``name::skin-tone-N`` (N 1..5) answers the toned
    sequence when the table has it, else None."""
    index = _table()
    if index is None or not isinstance(name, str):
        return None
    key = name.lower()
    base, sep, suffix = key.partition("::")
    if not sep:
        return index.by_code.get(key)
    tone = _TONE_SUFFIX_RE.fullmatch(suffix)
    if tone is None:
        return None
    return _toned(index, base, int(tone.group(1)))


def shortcodes(seq: str) -> tuple:
    """The Discord shortcodes of a sequence (either form); ``()`` if unknown."""
    entry = lookup(seq)
    return entry.shortcodes if entry is not None else ()


def replace_shortcodes(text: str) -> str:
    """``text`` with every KNOWN ``:name:`` replaced by its characters.

    ``:name::skin-tone-N:`` becomes the one toned emoji when the table has it.
    Unknown names (a server's custom emoji) are left exactly as written, and
    nothing inside a ``<...>`` token is touched -- ``<t:100:R>`` is a
    timestamp, ``<:name:123>`` a custom emoji."""
    if not text or ":" not in text:
        return text
    index = _table()
    if index is None:
        return text
    by_code = index.by_code
    out = []
    pos = 0
    while True:
        hit = _CODE_RE.search(text, pos)
        if hit is None:
            break
        name = hit.group(1)
        end = hit.end()
        if name is None:                       # a <...> token: copy it through
            out.append(text[pos:end])
            pos = end
            continue
        key = name.lower()
        seq = None
        tail = _TONE_TAIL_RE.match(text, end)
        if tail is not None:
            seq = _toned(index, key, int(tail.group(1)))
            if seq is not None:
                end = tail.end()
        if seq is None:
            seq = by_code.get(key)
        if seq is None:
            # Unknown: keep it, and let its closing colon open the next one.
            out.append(text[pos:end - 1])
            pos = end - 1
            continue
        out.append(text[pos:hit.start()])
        out.append(seq)
        pos = end
    out.append(text[pos:])
    return "".join(out)


# --------------------------------------------------------------------------
# search + groups
# --------------------------------------------------------------------------

def search(query: str, limit: int = 40) -> list:
    """Up to ``limit`` entries matching ``query``, best first.

    Case-insensitive. Shortcodes that START with the query come first, then
    shortcodes that contain it, then names that contain it; table order within
    each. Skin-tone variants are left out unless the query contains ``tone``.
    A space in the query matches an underscore in a shortcode and the other
    way round for names; surrounding colons are ignored. Empty query: ``[]``."""
    index = _table()
    if index is None or not isinstance(query, str) or limit <= 0:
        return []
    wanted = query.strip().strip(":").strip().lower()
    if not wanted:
        return []
    in_code = wanted.replace(" ", "_")
    in_name = wanted.replace("_", " ")
    with_tones = "tone" in wanted
    prefix, inside, named = [], [], []
    for entry, codes, name, toned in index.rows:
        if toned and not with_tones:
            continue
        rank = 3
        for code in codes:
            if code.startswith(in_code):
                rank = 0
                break
            if in_code in code:
                rank = 1
        if rank == 0:
            prefix.append(entry)
        elif rank == 1:
            inside.append(entry)
        elif in_name in name:
            named.append(entry)
    return (prefix + inside + named)[:limit]


def groups(include_tones: bool = False) -> list:
    """``[(group name, [Emoji, ...]), ...]`` in table order.

    Skin-tone variants (a sequence holding a modifier U+1F3FB..U+1F3FF) are
    left out unless ``include_tones`` -- a picker category is not 1,900 toned
    duplicates. The lists are the caller's own. ``[]`` without a table."""
    index = _table()
    if index is None:
        return []
    source = index.groups_all if include_tones else index.groups_plain
    return [(name, list(members)) for name, members in source]
