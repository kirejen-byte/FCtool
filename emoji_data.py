"""Lazy, thread-safe reader for the bundled emoji table (``emoji_table.json.gz``).

The table is Discord's standard emoji set -- Emoji 16.0's fully-qualified
sequences plus the 26 regional-indicator letters -- with each emoji's CLDR
name, Discord shortcodes, group and sprite-sheet tile.  It is generated by
``tools/build_emoji_pack.py``; this module is the ONLY thing that knows the
wire encoding.  Consumers (the ping editor's canvas, the tile cache, the
picker) go through the functions below.

Pure: the standard library and ``app_path`` only -- no Tk, no network, no
``fc_gui``.  (``app_log`` is imported inside the one function that emits the
one WARNING, never at import.)

**Importing this module opens no file and fetches no logger.**  The table is
decoded on the first call that needs it, once, under a lock; concurrent first
callers decode exactly once.  A missing, corrupt or misshaped table is never an
exception: the module logs ONE warning and then answers "no emoji" everywhere
(``available()`` False, ``split`` returns the text as one text chunk, lookups
return None) until :func:`set_data_file` points it somewhere else.

A table that cannot be READ (the file is not there, or the open / read raises
``OSError`` -- this box has a history of transient opens) is tried again by
later calls, at most three attempts in all.  A table that was read but is not a
valid table is given up on at once.  Either way there is at most one WARNING.

Wire encoding (gzip, UTF-8 JSON)::

    {"version": 1, "emoji_version": "16.0",
     "tile_px": 22, "cell_px": 24, "cols": 62,
     "count": <entries>, "tiles": <tiles in the sheet>,
     "emoji": [[seq, name, [shortcode, ...], group, tile], ...],
     "alt":   {"<not fully-qualified sequence>": position in "emoji", ...}}

``tile`` is explicit per entry and is NOT always the entry's position (a pack
built without skin-tone tiles gives a toned entry its base emoji's tile), so an
image is always found through :attr:`Emoji.tile`.

What counts as an emoji in text (:func:`split`)
-----------------------------------------------
The longest table sequence at each position, over the fully-qualified
sequences and the ``alt`` (minimally-qualified / unqualified) forms, with one
exception that keeps ordinary typing ordinary: **a single code point below
U+1F000 is an emoji only when it is ITSELF a fully-qualified entry** (the
characters with default emoji presentation -- the check mark U+2705, the star
U+2B50 and their like).  A single code point below U+1F000 that is only an
``alt`` form never matches, so a digit, ``#``, ``*``, the copyright, registered
and trade-mark signs and a bare U+2620 stay text; each becomes an emoji only as
part of a longer sequence (U+2620 U+FE0F, a keycap).
"""

import gzip
import json
import os
import re
import threading
from dataclasses import dataclass

from app_path import resolve_data_file

DATA_FILE = "emoji_table.json.gz"

#: The only wire version this reader understands.
_TABLE_VERSION = 1

#: Below this, a single code point that is only an ``alt`` form is never an
#: emoji (see the module docstring).  U+1F000 is where the pictographic planes
#: start; nothing below it that lacks default emoji presentation is something a
#: user means as a picture when it stands alone.
_TEXT_SINGLE_LIMIT = 0x1F000

_VS16 = chr(0xFE0F)
_TONE_FIRST, _TONE_LAST = 0x1F3FB, 0x1F3FF          # skin-tone modifiers 1..5
_TONE_RE = re.compile("[%s-%s]" % (chr(_TONE_FIRST), chr(_TONE_LAST)))

#: What separates an emoji from its toned forms: the modifiers and VS16.
_DETONE_RE = re.compile("[%s-%s%s]" % (chr(_TONE_FIRST), chr(_TONE_LAST), _VS16))

#: ``name::skin-tone-N`` -- Discord's long spelling of a toned emoji.
_TONE_SUFFIX_RE = re.compile(r"skin-tone-([1-5])")

#: One step of :func:`replace_shortcodes`: a ``<...>`` token (a Discord
#: timestamp, mention or custom emoji -- never touched) or a ``:name:``
#: candidate.  A token holds no whitespace, so ``1 < 2 :x: 3 > 2`` is not one.
#: A candidate's opening colon is at the start of the text or follows anything
#: but a letter, a digit or an underscore (``\w`` is Unicode-aware here) -- the
#: table has one- and two-letter names (``x``, ``b``, ``ok``, ``on``, ``up``),
#: so ``Comms:x:``, ``a:b:c``, a clock time and a URL must not be read as
#: shortcodes, while ``**:x:**``, ``(:x:)`` and ``:x::x:`` are.  (One more
#: rule is not in the pattern, because it depends on what the pass has done:
#: a DOUBLED colon opens nothing -- see :func:`replace_shortcodes`.)
_CODE_RE = re.compile(r"<[^<>\s]+>|(?<!\w):([^\s:<>]+):")
#: The ``:skin-tone-N:`` that may follow a ``:name:`` directly.
_TONE_TAIL_RE = re.compile(r":skin-tone-([1-5]):", re.IGNORECASE)

#: :func:`search`'s cap when the caller passes none, or one that is no positive int.
_DEFAULT_LIMIT = 40

#: Read attempts before a table that cannot be read is given up on.
_MAX_READ_ATTEMPTS = 3

#: Apostrophes dropped by :func:`_fold` (straight, and the two curly ones CLDR
#: names use -- "man's shoe", "twelve o'clock").
_APOSTROPHES = {ord("'"): None, 0x2018: None, 0x2019: None}


def _fold(text: str) -> str:
    """``text`` for searching: lower-case, accents and apostrophes dropped, so
    ``pinata`` finds the n-tilde name and ``cote d'ivoire`` its flag.

    ``unicodedata`` is imported here, on the rare non-ASCII string, so that
    importing this module loads nothing extra."""
    text = text.lower()
    if text.isascii():
        return text.replace("'", "") if "'" in text else text
    import unicodedata
    text = "".join(ch for ch in unicodedata.normalize("NFKD", text)
                   if not unicodedata.combining(ch))
    return text.translate(_APOSTROPHES)


@dataclass(frozen=True)
class Emoji:
    """One table entry. ``tile`` is the entry's sheet tile (see the module
    docstring), ``shortcodes`` its Discord names without colons."""
    seq: str
    name: str
    shortcodes: tuple
    tile: int
    group: str


@dataclass(frozen=True)
class SheetLayout:
    """The sprite sheet's grid: ``tiles`` tiles of ``tile_px`` in ``cell_px``
    cells, ``cols`` to a row."""
    tile_px: int
    cell_px: int
    cols: int
    tiles: int


# --------------------------------------------------------------------------
# the decoded table
# --------------------------------------------------------------------------

class _Index:
    """Everything derived from one table, built once at load so that no call
    after it scans more than it has to.  Immutable after :func:`_build`."""
    __slots__ = ("layout", "by_seq", "alt", "by_code", "match", "lengths",
                 "find_start", "rows", "groups_all", "groups_plain")


def _is_int(value) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def _start_pattern(chars):
    """A compiled character class used to jump straight to the next position
    where an emoji could start.

    It matches every code point of ``chars`` and may match MORE: the ones
    above U+FFFF are folded into one range, first to last.  ``re`` tests a
    class's astral ranges one by one for every character it rejects, so the
    exact class (some hundred ranges on the real table) made plain text three
    times slower to scan than this superset; :func:`split` discards the few
    false candidates with one dict lookup."""
    points = sorted(ord(ch) for ch in chars)
    astral = [point for point in points if point > 0xFFFF]
    points = [point for point in points if point <= 0xFFFF]
    parts = []
    if astral:
        parts.append(re.escape(chr(astral[0])) + "-" + re.escape(chr(astral[-1])))
    i = 0
    while i < len(points):
        j = i
        while j + 1 < len(points) and points[j + 1] == points[j] + 1:
            j += 1
        first, last = re.escape(chr(points[i])), re.escape(chr(points[j]))
        parts.append(first if i == j else first + "-" + last)
        i = j + 1
    return re.compile("[" + "".join(parts) + "]")


def _build(table) -> _Index:
    """Validate ``table`` and index it. Raises ``ValueError`` on any shape
    problem; :func:`_load` turns that into "unavailable"."""
    if not isinstance(table, dict):
        raise ValueError("top level is %s, expected object" % type(table).__name__)
    version = table.get("version")
    if not _is_int(version) or version != _TABLE_VERSION:
        raise ValueError("table version is %r, expected %d"
                         % (version, _TABLE_VERSION))
    for key in ("tile_px", "cell_px", "cols", "tiles"):
        if not _is_int(table.get(key)) or table[key] <= 0:
            raise ValueError("%r is %r, expected a positive integer"
                             % (key, table.get(key)))
    raw = table.get("emoji")
    raw_alt = table.get("alt")
    if not isinstance(raw, list) or not raw:
        raise ValueError("'emoji' is missing or empty")
    if not isinstance(raw_alt, dict):
        raise ValueError("'alt' is missing or not an object")
    if "count" in table and not (_is_int(table["count"])
                                 and table["count"] == len(raw)):
        raise ValueError("'count' is %r but there are %d entries"
                         % (table["count"], len(raw)))

    entries = []
    by_seq = {}
    by_code = {}
    for position, row in enumerate(raw):
        if not isinstance(row, (list, tuple)) or len(row) < 5:
            raise ValueError("entry %d is misshaped" % position)
        seq, name, codes, group, tile = row[:5]
        if not (isinstance(seq, str) and seq
                and isinstance(name, str) and isinstance(group, str)
                and isinstance(codes, (list, tuple))
                and all(isinstance(code, str) for code in codes)
                and _is_int(tile) and 0 <= tile < table["tiles"]):
            raise ValueError("entry %d is misshaped" % position)
        entry = Emoji(seq, name, tuple(codes), tile, group)
        entries.append(entry)
        by_seq.setdefault(seq, entry)
        for code in codes:
            by_code.setdefault(code.lower(), seq)

    alt = {}
    for key, position in raw_alt.items():
        if not (isinstance(key, str) and key and _is_int(position)
                and 0 <= position < len(entries)):
            raise ValueError("alt form %r is misshaped" % (key,))
        if key not in by_seq:
            alt[key] = entries[position]

    # What split() may match: every fully-qualified sequence, and every alt
    # form EXCEPT a single code point below the pictographic planes.
    match = set(by_seq)
    for key in alt:
        if len(key) == 1 and ord(key) < _TEXT_SINGLE_LIMIT:
            continue
        match.add(key)
    by_start = {}
    for seq in match:
        by_start.setdefault(seq[0], set()).add(len(seq))

    rows = []
    groups_all = {}
    groups_plain = {}
    for entry in entries:
        toned = _TONE_RE.search(entry.seq) is not None
        rows.append((entry, tuple(_fold(code) for code in entry.shortcodes),
                     _fold(entry.name), toned))
        groups_all.setdefault(entry.group, []).append(entry)
        if not toned:
            groups_plain.setdefault(entry.group, []).append(entry)

    index = _Index()
    index.layout = SheetLayout(table["tile_px"], table["cell_px"],
                               table["cols"], table["tiles"])
    index.by_seq = by_seq
    index.alt = alt
    index.by_code = by_code
    index.match = frozenset(match)
    index.lengths = {first: tuple(sorted(lengths, reverse=True))
                     for first, lengths in by_start.items()}
    index.find_start = _start_pattern(by_start).search
    index.rows = tuple(rows)
    index.groups_all = tuple((name, tuple(members))
                             for name, members in groups_all.items())
    index.groups_plain = tuple((name, tuple(members))
                               for name, members in groups_plain.items())
    return index


# --------------------------------------------------------------------------
# module state + loading
# --------------------------------------------------------------------------

_UNSET = object()

#: ``_UNSET`` until the table's fate is settled; afterwards the :class:`_Index`,
#: or None when the table could not be used.  Rebound as a whole (never
#: mutated), so a reader needs no lock.
_cache = _UNSET
#: :func:`set_data_file`'s path, or None for the bundled copy.
_override = None
#: Loads tried since the last :func:`set_data_file` (see ``_MAX_READ_ATTEMPTS``).
_attempts = 0
#: Whether the one WARNING has been logged since the last :func:`set_data_file`.
_warned = False
_lock = threading.Lock()


def _data_path():
    """The table's path, or None when the bundled copy is not present.

    ``prefer="bundle"``: a PRISTINE generated table that must always read the
    packaged copy and never be shadowed by a stray file in the writable dir."""
    if _override is not None:
        return _override
    return resolve_data_file(DATA_FILE, prefer="bundle")


def _read_bytes(path) -> bytes:
    """The file's raw bytes. The ONLY disk access of a load, kept apart from
    :func:`_parse` so that an ``OSError`` here means "could not read" (worth
    another try) and never "bad content" -- ``gzip.BadGzipFile`` is itself an
    ``OSError`` and would blur the two.  Also the seam the load-once and retry
    contracts are spied on through."""
    with open(path, "rb") as fh:
        return fh.read()


def _parse(data: bytes):
    """Gunzip + decode + parse. Raises on anything that is not a gzip of UTF-8
    JSON (a truncated stream included)."""
    return json.loads(gzip.decompress(data).decode("utf-8"))


def _log(level: str, message: str, *args) -> None:
    """One line through the house logger -- fetched HERE, never at import,
    because its first call opens the log file.  Never raises."""
    try:
        from app_log import get_logger
        getattr(get_logger(__name__), level)(message, *args)
    except Exception:
        pass


def _reason(exc) -> str:
    """``exc`` for a log line, WITHOUT a directory: a path can carry a Windows
    user name, and logs get shared for support.

    An ``OSError`` is written as its type, then its ``strerror`` when it has
    one (the system's own reason -- or this module's, see :func:`_load`), then
    the LAST component of the path it names, if it names one.  Never
    ``str(exc)``: that spells the whole path, and an error without a
    ``strerror`` can spell anything.  Anything else is written as its type
    name only -- its text is not ours."""
    why = type(exc).__name__
    if isinstance(exc, OSError):
        if exc.strerror:
            why = "%s: %s" % (why, exc.strerror)
        if exc.filename is not None:
            try:
                name = os.path.basename(os.fspath(exc.filename))
            except TypeError:                 # a file descriptor, not a path
                name = "?"
            why = "%s: %r" % (why, name)
    return why


def _warn_once(message: str, *args) -> None:
    """The one WARNING of a run; later problems are silent."""
    global _warned
    if _warned:
        return
    _warned = True
    _log("warning", message, *args)


def _load():
    """One load attempt -> ``(index or None, settled)``. Never raises. Called
    with ``_lock`` held.

    ``settled`` False means "could not read it, a later call may try again";
    it turns True on the last allowed attempt."""
    global _attempts
    _attempts += 1
    settled = _attempts >= _MAX_READ_ATTEMPTS
    try:
        path = _data_path()
        if not path:
            # (errno, strerror): the wording is logged as is (see _reason).
            raise FileNotFoundError(2, "not found beside the app")
        data = _read_bytes(path)
    except OSError as exc:
        _warn_once("[Emoji] %s could not be read (%s); emoji are shown as "
                   "plain characters", DATA_FILE, _reason(exc))
        return None, settled
    except Exception as exc:                  # a path that is no path at all
        _warn_once("[Emoji] %s could not be located (%s); emoji are shown "
                   "as plain characters", DATA_FILE, _reason(exc))
        return None, True
    try:
        table = _parse(data)
    except Exception as exc:
        _warn_once("[Emoji] %s is unusable (%s); emoji are shown as plain "
                   "characters", DATA_FILE, _reason(exc))
        return None, True
    try:
        index = _build(table)
    except ValueError as exc:
        # _build's own words about the table's SHAPE (a version, a count, an
        # entry's position): written by this module, never a path.
        _warn_once("[Emoji] %s is unusable (%s); emoji are shown as plain "
                   "characters", DATA_FILE, exc)
        return None, True
    except Exception as exc:
        _warn_once("[Emoji] %s is unusable (%s); emoji are shown as plain "
                   "characters", DATA_FILE, _reason(exc))
        return None, True
    if _attempts > 1:
        _log("info", "[Emoji] %s read on attempt %d", DATA_FILE, _attempts)
    return index, True


def _table():
    """The index, loading it on first use; None when there is no usable table
    (or not yet -- see :func:`_load`)."""
    global _cache
    cache = _cache
    if cache is not _UNSET:
        return cache
    with _lock:
        if _cache is not _UNSET:
            return _cache
        index, settled = _load()
        if settled:
            _cache = index
        return index


def set_data_file(path) -> None:
    """Test seam: read the table from ``path`` instead of the bundled copy
    (``None`` restores the bundled copy) and forget whatever was loaded.
    Reads nothing itself -- the next call that needs the table does."""
    global _cache, _override, _attempts, _warned
    with _lock:
        _override = None if path is None else os.fspath(path)
        _cache = _UNSET
        _attempts = 0
        _warned = False


def available() -> bool:
    """Whether a usable table is loaded (loading it if this is the first call).
    False when it is missing or corrupt -- one WARNING is logged, once.

    A False can be PROVISIONAL: a table that could not be READ (a transient
    open / read failure) is tried again by a later call, at most
    ``_MAX_READ_ATTEMPTS`` times in all, so a later call may answer True. Ask
    again when it matters; do not cache a False."""
    return _table() is not None


def sheet_layout() -> "SheetLayout | None":
    """The sprite sheet's grid, or None without a table."""
    index = _table()
    return None if index is None else index.layout


