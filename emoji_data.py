# shortcodes
# --------------------------------------------------------------------------

def _toned(index, base: str, tone: int) -> "str | None":
    """The sequence for shortcode ``base`` (lower-case) in skin tone 1..5, or
    None when the table has no such emoji.

    Discord's own ``<base>_tone<N>`` name first -- but ONLY when that entry is
    a toned form of ``base``'s own emoji (the same sequence once modifiers and
    VS16 are removed).  The names do not guarantee it: ``kiss`` is the lips
    while ``kiss_tone3`` is a couple, and answering the couple would swap what
    the user wrote for a different emoji.  Failing that the sequence is built
    -- modifier after the first code point, a VS16 there dropped -- and
    accepted only if it is a table entry."""
    plain = index.by_code.get(base)
    if plain is None:
        return None
    named = index.by_code.get("%s_tone%d" % (base, tone))
    if (named is not None and named != plain
            and _DETONE_RE.sub("", named) == _DETONE_RE.sub("", plain)):
        return named
    rest = plain[1:]
    if rest.startswith(_VS16):
        rest = rest[1:]
    built = plain[0] + chr(_TONE_FIRST + tone - 1) + rest
    return built if built in index.by_seq else None


def from_shortcode(name: str) -> "str | None":
    """The sequence for a Discord shortcode given WITHOUT colons, or None.

    Case-insensitive. ``name::skin-tone-N`` (N 1..5) answers the toned
    sequence when the table has it, else None."""
    index = _table()
    if index is None or not isinstance(name, str):
        return None
    key = name.lower()
    base, sep, suffix = key.partition("::")
    if not sep:
        return index.by_code.get(key)
    tone = _TONE_SUFFIX_RE.fullmatch(suffix)
    if tone is None:
        return None
    return _toned(index, base, int(tone.group(1)))


def shortcodes(seq: str) -> tuple:
    """The Discord shortcodes of a sequence (either form); ``()`` if unknown."""
    entry = lookup(seq)
    return entry.shortcodes if entry is not None else ()


def _name_like(name: str) -> bool:
    """Whether an UNKNOWN ``:name:`` may be followed directly by another
    shortcode: non-empty, and every character a letter, a digit or one of
    ``_ + -`` -- the characters a typed ``:`` query is made of.  An emoji
    character or punctuation is none of those, so the colon after ``:a.b:``
    or ``:-):`` stays a doubled colon.  ``pill_canvas._emoji_colon_ok`` spells
    the same test for the typed path; the shared rows keep the two in step."""
    return bool(name) and all(ch.isalnum() or ch in "_+-" for ch in name)


def replace_shortcodes(text: str) -> str:
    """``text`` with every KNOWN ``:name:`` replaced by its characters, in one
    left-to-right pass.

    A ``:name:`` counts only when its opening colon is at the start of the text
    or does NOT follow a letter, a digit or an underscore.  So ``Comms:x:``,
    ``a:b:c``, ``19:00:skull:``, ``:nope:skull:`` and a URL are left alone,
    while ``**:skull:**``, ``(:skull:)``, shortcodes written back to back and
    one straight after a ``<...>`` token convert, as Discord does.
    ``:name::skin-tone-N:`` becomes the one toned emoji when the table has it
    (else ``:name:`` alone is replaced).  Unknown names (a server's custom
    emoji) are left exactly as written, and nothing inside a ``<...>`` token
    is touched -- ``<t:100:R>`` is a timestamp, ``<:name:123>`` a custom emoji.

    **A doubled colon opens nothing**: an opening colon directly preceded by a
    raw ``:`` is not one, so ``PING::x:up``, ``::x:`` and ``std::x:`` are left
    alone.  The one exception is the colon that CLOSED a well-formed ``:name:``
    this very pass has just read, whose own opening colon passed these rules:
    a name it converted, or an UNKNOWN one it left as written (a server's
    custom emoji) -- and an unknown one counts only when it looks like a name
    (:func:`_name_like`: letters, digits, ``_ + -``).  So shortcodes written
    back to back convert (``:skull::skull:``), so does a known one straight
    after an unknown one (``:custom::skull:``, ``:a::b::skull:``), and what
    follows a converted ``:name:`` (a ``:skin-tone-N:`` the table has no emoji
    for included) is read as before -- while ``:a.b::skull:``, ``:-)::skull:``
    and a "name" holding an emoji character open nothing.  The typed path
    applies the same rule (``pill_canvas._emoji_colon_ok``)."""
    if not text or ":" not in text:
        return text
    index = _table()
    if index is None:
        return text
    by_code = index.by_code
    find = _CODE_RE.search
    out = []
    pos = 0             # start of the text not yet emitted
    scan = 0            # where the search for the next candidate resumes
    glued = -1          # just past the ``:name:`` this pass read last
    while True:
        hit = find(text, scan)
        if hit is None:
            break
        name = hit.group(1)
        start = hit.start()
        end = hit.end()
        if name is None:                       # a <...> token: as written
            out.append(text[pos:end])
            pos = scan = end
            continue
        if start and text[start - 1] == ":" and start != glued:
            # A doubled colon whose first colon closed no ``:name:``: this one
            # opens nothing. Look again after it -- the candidate's own
            # closing colon may still open a shortcode.
            scan = start + 1
            continue
        key = name.lower()
        seq = None
        tail = _TONE_TAIL_RE.match(text, end)
        if tail is not None:
            seq = _toned(index, key, int(tail.group(1)))
            if seq is not None:
                end = tail.end()
        if seq is None:
            seq = by_code.get(key)
        if seq is None:
            # Unknown: keep it and look again FROM its closing colon. Whether
            # that colon may open a shortcode is the same question as for any
            # other: not after the letter that ends ``:nope:``, but yes after
            # the bracket that ends ``:-):``.
            # (And a name may follow it directly -- ``:custom::skull:`` -- when
            # what it closes looks like a name.)
            out.append(text[pos:end - 1])
            pos = scan = end - 1
            if _name_like(name):
                glued = end
            continue
        out.append(text[pos:start])
        out.append(seq)
        pos = scan = glued = end
    out.append(text[pos:])
    return "".join(out)


